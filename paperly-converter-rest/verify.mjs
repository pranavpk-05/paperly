import { chromium } from 'playwright';
import assert from 'node:assert/strict';
import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

const base = new URL('./', import.meta.url);
const artifacts = fileURLToPath(new URL('./artifacts/', base));
await mkdir(artifacts, { recursive: true });
const browser = await chromium.launch({ headless: true, channel: 'chrome' });
const page = await browser.newPage({ viewport: { width: 1440, height: 1060 } });
const errors = [];
const checks = [];
page.on('pageerror', error => errors.push(error.message));
const check = (name) => { checks.push(name); console.log(`PASS ${name}`); };
async function parseDownload(download) {
  const target = `${artifacts}/${download.suggestedFilename()}`;
  await download.saveAs(target);
  const bytes = await readFile(target);
  assert.equal(bytes.subarray(0, 5).toString(), '%PDF-');
  return page.evaluate(async data => {
    const doc = await PDFLib.PDFDocument.load(new Uint8Array(data));
    return { pages: doc.getPages().map(page => page.getSize()), title: doc.getTitle() };
  }, Array.from(bytes));
}
try {
  const response = await page.goto((process.env.PAPERLY_BASE_URL || 'http://127.0.0.1:4178').replace(/\/$/, '') + '/image-to-pdf/index.html', { waitUntil: 'networkidle' });
  assert.equal(response.status(), 200);
  assert(await page.locator('#convert-button').isDisabled());
  assert.equal(await page.locator('.art-card img').evaluateAll(images => images.every(img => img.complete && img.naturalWidth > 0)), true);
  await page.screenshot({ path: `${artifacts}/desktop.png`, fullPage: true });
  check('Initial UI, locally served images, disabled empty export');
  await page.locator('#how-button').click();
  assert(await page.locator('#help-dialog').isVisible());
  await page.keyboard.press('Escape');
  check('Help dialog and keyboard dismissal');
  await page.locator('#sample-button').click();
  await page.waitForFunction(() => document.querySelectorAll('.image-card').length === 3);
  assert.equal(await page.locator('#page-summary').textContent(), '3 images → 3 pages');
  check('Sample images load into the actual conversion queue');
  await page.getByRole('button', { name: 'Move page 1 later', exact: true }).click();
  assert.equal(await page.locator('.image-name').first().textContent(), 'lake.jpg');
  await page.locator('.image-card').first().dragTo(page.locator('.image-card').last());
  assert.equal(await page.locator('.image-name').last().textContent(), 'lake.jpg');
  check('Both keyboard buttons and drag-and-drop reorder pages');
  await page.getByRole('button', { name: 'Rotate page 1 clockwise', exact: true }).click();
  assert.equal(await page.locator('.image-thumb img').first().evaluate(img => img.style.transform), 'rotate(90deg)');
  await page.locator('#preview-button').click();
  await page.locator('#preview-dialog').waitFor({ state: 'visible' });
  const previewData = await page.evaluate(async () => {
    const frame = document.querySelector('#pdf-preview');
    const doc = await PDFLib.PDFDocument.load(await fetch(frame.src).then(r => r.arrayBuffer()));
    return doc.getPages().map(page => page.getSize());
  });
  assert.equal(previewData.length, 3);
  assert(previewData[0].height > previewData[0].width, 'Rotation should affect automatic orientation');
  check('Rotation, actual generated PDF preview, and automatic page orientation');
  const previewDownload = page.waitForEvent('download');
  await page.locator('#preview-download').click();
  assert.equal((await parseDownload(await previewDownload)).pages.length, 3);
  await page.locator('#preview-dialog [data-close]').click();
  check('Preview download produces a parseable three-page PDF');
  await page.locator('#page-size').selectOption('letter');
  await page.locator('[data-orientation="landscape"]').click();
  await page.locator('[data-margin="48"]').click();
  await page.locator('#quality').uncheck();
  await page.locator('#filename').fill('Weekend memories');
  const downloadPromise = page.waitForEvent('download');
  await page.locator('#convert-button').click();
  const download = await downloadPromise;
  assert.equal(download.suggestedFilename(), 'Weekend memories.pdf');
  const pdf = await parseDownload(download);
  assert.equal(pdf.title, 'Weekend memories');
  assert(pdf.pages.every(p => p.width === 792 && p.height === 612));
  check('US Letter landscape, large margins, compressed mode, custom name and valid PDF download');
  await page.getByRole('button', { name: 'Remove page 2', exact: true }).click();
  assert.equal(await page.locator('.image-card').count(), 2);
  await page.locator('#clear-button').click();
  assert(await page.locator('#empty-state').isVisible());
  assert(await page.locator('#convert-button').isDisabled());
  check('Remove image and clear workspace');
  await page.locator('#file-input').setInputFiles({ name: 'notes.txt', mimeType: 'text/plain', buffer: Buffer.from('not an image') });
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('please use'));
  assert.equal(await page.locator('.image-card').count(), 0);
  check('Unsupported files are rejected with a visible explanation');
  const testImages = await page.evaluate(() => {
    const canvas = document.createElement('canvas'); canvas.width = 240; canvas.height = 120;
    const ctx = canvas.getContext('2d'); ctx.fillStyle = '#7960d8'; ctx.fillRect(20, 20, 100, 80);
    return ['image/png', 'image/webp'].map(type => ({ type, data: canvas.toDataURL(type).split(',')[1] }));
  });
  await page.locator('#file-input').setInputFiles(testImages.map((image, i) => ({ name: `test-${i}.${i ? 'webp' : 'png'}`, mimeType: image.type, buffer: Buffer.from(image.data, 'base64') })));
  await page.waitForFunction(() => document.querySelectorAll('.image-card').length === 2);
  await page.locator('#page-size').selectOption('original');
  await page.locator('[data-orientation="auto"]').click();
  await page.locator('[data-margin="0"]').click();
  const fitDownload = page.waitForEvent('download');
  await page.locator('#convert-button').click();
  const fitPdf = await parseDownload(await fitDownload);
  assert(fitPdf.pages.every(p => p.width === 180 && p.height === 90));
  check('PNG and WebP upload, image-sized pages, and zero margins');
  await page.locator('#clear-button').click();
  const jpg = await readFile(new URL('./dist/assets/forest.jpg', base));
  const dataTransfer = await page.evaluateHandle(data => {
    const dt = new DataTransfer(); dt.items.add(new File([new Uint8Array(data)], 'dropped-forest.jpg', { type: 'image/jpeg' })); return dt;
  }, Array.from(jpg));
  await page.locator('#drop-zone').dispatchEvent('drop', { dataTransfer });
  await page.waitForFunction(() => document.querySelectorAll('.image-card').length === 1);
  check('Dropping a local JPG adds it to the workspace');
  await page.screenshot({ path: `${artifacts}/workspace.png`, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${artifacts}/mobile.png`, fullPage: true });
  check('Mobile layout has no horizontal overflow');
  assert.deepEqual(errors, []);
  check('No browser JavaScript errors across the full journey');
  await writeFile(`${artifacts}/verification.json`, JSON.stringify({ passed: checks, browserErrors: errors }, null, 2));
} finally { await browser.close(); }
